import { createHash } from 'node:crypto'
import {
  coreNames,
  tokens as defaultTokens,
  fontNames,
  radiusNames,
  roleNames,
  spaceSteps,
  type Theme,
  type Tokens,
  terrainNames,
  washNames
} from './tokens.ts'

/** One custom property declaration. */
export type Declaration = readonly [property: string, value: string]

/** A rule block, optionally nested in an at-rule such as a media query. */
export interface CssBlock {
  readonly atRule?: string
  readonly selector: string
  readonly declarations: readonly Declaration[]
}

const fontStack = (families: readonly string[]): string =>
  families.map((f) => (/^[a-z-]+$/i.test(f) && !f.includes(' ') ? f : `'${f}'`)).join(', ')

/** Bare role variables (`--paper`, `--ink`, `--wash-ok`, …) for one theme, plus `color-scheme`. */
function themeDeclarations(t: Tokens, theme: Theme): Declaration[] {
  return [
    ['color-scheme', theme === 'night' ? 'dark' : 'light'],
    ...roleNames.map((role): Declaration => [`--${role}`, t.roles[theme][role]]),
    ...washNames.map((wash): Declaration => [`--wash-${wash}`, t.washes[theme][wash]])
  ]
}

/** Theme-independent variables in the Tailwind v4 namespaces, plus spacing, radii and motion. */
function staticDeclarations(t: Tokens): Declaration[] {
  return [
    // Core names that are also role names (ink, teal) take the theme-aware role alias instead.
    ...coreNames
      .filter((name) => !(roleNames as readonly string[]).includes(name))
      .map((name): Declaration => [`--color-${name}`, t.core[name]]),
    ...roleNames.map((role): Declaration => [`--color-${role}`, `var(--${role})`]),
    ...washNames.map((wash): Declaration => [`--color-wash-${wash}`, `var(--wash-${wash})`]),
    ...terrainNames.map((name): Declaration => [`--color-terrain-${name}`, t.terrain[name]]),
    ...fontNames.map((name): Declaration => [`--font-${name}`, fontStack(t.fonts[name])]),
    ...spaceSteps.map((step): Declaration => [`--space-${step}`, t.space[step]]),
    ...radiusNames.map((name): Declaration => [`--radius-${name}`, t.radius[name]]),
    ['--motion-fps', String(t.motion.fps)],
    ['--motion-cycle', String(t.motion.cycle)],
    ['--motion-frame', `${(1000 / t.motion.fps).toFixed(3)}ms`]
  ]
}

/**
 * The stylesheet as blocks: light on `:root`, night under `prefers-color-scheme: dark` (unless the page pins
 * `data-theme="light"`) and under `[data-theme="night"]`.
 */
export function cssBlocks(t: Tokens = defaultTokens): CssBlock[] {
  return [
    { selector: ':root', declarations: [...themeDeclarations(t, 'light'), ...staticDeclarations(t)] },
    {
      atRule: '@media (prefers-color-scheme: dark)',
      selector: ':root:not([data-theme="light"])',
      declarations: themeDeclarations(t, 'night')
    },
    { selector: '[data-theme="night"]', declarations: themeDeclarations(t, 'night') },
    { selector: '[data-theme="light"]', declarations: themeDeclarations(t, 'light') }
  ]
}

function renderBlock({ atRule, selector, declarations }: CssBlock): string {
  const indent = atRule ? '    ' : '  '
  const body = declarations.map(([p, v]) => `${indent}${p}: ${v};`).join('\n')
  const rule = `${atRule ? '  ' : ''}${selector} {\n${body}\n${atRule ? '  ' : ''}}`
  return atRule ? `${atRule} {\n${rule}\n}` : rule
}

const HEADER = '/* Generated by @knowledgeislands/tokens from tokens.json. Do not edit. */'

/** Renders `dist/tokens.css`. */
export function renderCss(blocks: readonly CssBlock[] = cssBlocks()): string {
  return `${HEADER}\n${blocks.map(renderBlock).join('\n\n')}\n`
}

/**
 * Renders `dist/theme.css` for Tailwind v4: literal values in `@theme`, and the theme-aware role aliases in
 * `@theme inline` so utilities such as `bg-paper` follow light and night.
 */
export function renderTailwindTheme(t: Tokens = defaultTokens): string {
  const themed = (p: string) => p.startsWith('--color-') || p.startsWith('--font-') || p.startsWith('--radius-')
  const declarations = staticDeclarations(t).filter(([p]) => themed(p))
  const body = (list: readonly Declaration[]) => list.map(([p, v]) => `  ${p}: ${v};`).join('\n')
  const literal = declarations.filter(([, v]) => !v.startsWith('var('))
  const aliases = declarations.filter(([, v]) => v.startsWith('var('))
  return `${HEADER}\n@import './tokens.css';\n\n@theme {\n${body(literal)}\n}\n\n@theme inline {\n${body(aliases)}\n}\n`
}

/**
 * SHA-256 of the declarations in canonical form (`at-rule|selector|property:value` per line), so formatting and
 * comments never change it. The Observatory pins this when it vendors the stylesheet.
 */
export function cssDigest(blocks: readonly CssBlock[] = cssBlocks()): string {
  const canonical = blocks
    .flatMap(({ atRule = '', selector, declarations }) =>
      declarations.map(([p, v]) => `${atRule}|${selector}|${p}:${v}`)
    )
    .join('\n')
  return createHash('sha256').update(canonical).digest('hex')
}

/** Renders `dist/tokens.ts`: the resolved values as a typed constant. */
export function renderTokensModule(t: Tokens = defaultTokens): string {
  return `// Generated by @knowledgeislands/tokens from tokens.json. Do not edit.\nexport const tokens = ${JSON.stringify(t, null, 2)} as const\n\nexport type Tokens = typeof tokens\n`
}
