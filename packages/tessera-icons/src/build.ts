/** Reads `svg/*.svg`, lints each glyph and writes `src/icons.generated.ts`. Run with `bun run build`. */
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { lintIcon } from './lint.ts'

const svgDir = new URL('../svg/', import.meta.url)
const files = (await readdir(svgDir)).filter((file) => file.endsWith('.svg')).sort()

const quote = (text: string): string => `'${text.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
const failures: string[] = []
const entries: string[] = []

for (const file of files) {
  const name = file.slice(0, -'.svg'.length)
  const source = await readFile(new URL(file, svgDir), 'utf8')
  for (const problem of lintIcon(source)) failures.push(`${file}: ${problem}`)
  const body = source
    .replace(/^\s*<svg\b[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('')
  // Match Biome's output so the generated file is stable under `biome check --write`.
  const key = /^[a-z]\w*$/i.test(name) ? name : quote(name)
  const entry = `  ${key}: ${quote(body)}`
  // Biome keeps keys narrower than five columns on the same line however long the value is.
  entries.push(entry.length + 1 > 120 && key.length >= 5 ? `  ${key}:\n    ${quote(body)}` : entry)
}

if (failures.length > 0) {
  console.error(failures.join('\n'))
  process.exit(1)
}

const names = files.map((file) => quote(file.slice(0, -'.svg'.length)))
const output = `// Generated by src/build.ts from svg/*.svg. Do not edit; run \`bun run build\`.

export const iconNames = [
${names.map((name) => `  ${name}`).join(',\n')}
] as const

export type IconName = (typeof iconNames)[number]

/** Inner markup of each glyph, without the root <svg>. */
export const iconBodies: Readonly<Record<IconName, string>> = {
${entries.join(',\n')}
}
`
await writeFile(new URL('icons.generated.ts', import.meta.url), output)
console.log(`icons: wrote ${files.length} glyphs to src/icons.generated.ts`)
